/** Package the user's cursor drawings as self-contained SVGs. No runtime file reads. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const directory = new URL('../ICONS/illustrator/redraw/', import.meta.url);
const target = new URL('../renderer/draw/tools/cursor-artwork.mjs', import.meta.url);
// Editable drawings are local and gitignored. Fresh checkouts use the committed
// artwork module; the cursor tests still validate all packaged assets and mappings.
if (!existsSync(directory) && process.argv.includes('--check')) {
  await import(target.href);
  console.log('Custom cursors: using packaged artwork (local source drawings unavailable)');
  process.exit(0);
}
const artwork = {};
for (const name of readdirSync(directory).filter(name => /^Cur_.*\.svg$/.test(name)).sort()) {
  const source = readFileSync(new URL(name, directory), 'utf8').replace(/\r\n/g, '\n');
  const match = source.match(/<svg\b[^>]*viewBox="0 0 64 64"[^>]*>([\s\S]*)<\/svg>\s*$/);
  if (!match || /<(?:script|foreignObject|image|use)\b|\bon\w+\s*=|(?:href\s*=|url\s*\()/i.test(match[1])) {
    throw new Error(`Expected a self-contained 64 × 64 cursor drawing: ${name}`);
  }
  // Explicit dimensions are required for SVG cursor images. Preserve the original
  // coordinate system, shapes, colors and transparency; @2x artwork displays at 32px.
  artwork[name] = `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 64 64">${match[1].replace(/\s*<!--[\s\S]*?-->\s*/g, '\n')}</svg>`;
}
if (!Object.keys(artwork).length) throw new Error('No custom cursor drawings found.');
const output = `// Generated by npm run build:cursors from ICONS/illustrator/redraw/Cur_*.svg.\n// Edit the source drawings, then rebuild.\nexport const CURSOR_ARTWORK = Object.freeze(${JSON.stringify(artwork, null, 2)});\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Cursor artwork is stale. Run npm run build:cursors.');
} else writeFileSync(target, output);
console.log(`Custom cursors: ${Object.keys(artwork).length} ${process.argv.includes('--check') ? 'verified' : 'packaged'}`);
